n = int(input())

if n < 100: # 2자리 수 이하
    ans = n
elif n == 1000:
    ans = 144
else: # 3자리수
    ans = 99
    for i in range(100, n+1):
        a = i // 100 # 백의자리 수
        b = i // 10 - a * 10 # 십의자리 수
        c = i % 10 # 일의자리 수
        if(a-b == b-c): # 등차수열이면
            ans += 1

print(ans)
